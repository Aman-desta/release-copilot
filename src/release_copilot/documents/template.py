"""The release document's fixed template: the sections, which ones must cite every sentence, and how it renders.

The writer fills a ``DocumentDraft`` (one Markdown body per section) through structured output; code renders the
title, the facts table and the headings. So the model can't drop a section, reorder the document or edit a number
in the table: the shape is code, only the prose is the model's.
"""

from dataclasses import dataclass

from pydantic import BaseModel, ConfigDict, Field

from release_copilot.documents.facts import ReleaseFacts, facts_table

BODY_RULES = (
    "Markdown paragraphs or '- ' bullets only, no headings or tables. "
    "End every factual sentence with its citations in square brackets before the full stop, e.g. "
    "'PAY-102 adds idempotent capture [jira:PAY-102] [gh:pr:412].'"
)


class DocumentDraft(BaseModel):
    """The writer's answer: the body of each section of the release document."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    summary: str = Field(description="Two to four sentences: what the release does and whether it looks ready. " + BODY_RULES)
    scope: str = Field(description="The tickets in the release, one bullet each, with type and status. " + BODY_RULES)
    changes: str = Field(description="What changed, grouped by area (component or folder), citing PRs and commits. " + BODY_RULES)
    quality: str = Field(description="CI checks, the quality gate, coverage and every open security alert. " + BODY_RULES)
    deployment: str = Field(description="Where it deploys, what production runs now, and database migrations. " + BODY_RULES)
    risks: str = Field(description="Every risk, most severe first: blocking alerts, failing gate or checks, untracked commits, missing evidence. " + BODY_RULES)
    rollback: str = Field(description="How to roll back: swap back to the production release and any migration caveat. " + BODY_RULES)


@dataclass(frozen=True)
class SectionSpec:
    key: str  # the DocumentDraft field
    title: str
    cited: bool  # every sentence must cite evidence (a "required section")


SECTIONS: tuple[SectionSpec, ...] = (
    SectionSpec("summary", "Summary", cited=False),  # a synthesis of the sections below, which carry the citations
    SectionSpec("scope", "Scope", cited=True),
    SectionSpec("changes", "Changes by area", cited=True),
    SectionSpec("quality", "Quality and security", cited=True),
    SectionSpec("deployment", "Deployment and migration notes", cited=True),
    SectionSpec("risks", "Risks", cited=True),
    SectionSpec("rollback", "Rollback summary", cited=False),  # a procedure, not a claim; its facts are cited above
)
SECTION_KEYS: tuple[str, ...] = tuple(s.key for s in SECTIONS)
CITED_SECTIONS: frozenset[str] = frozenset(s.key for s in SECTIONS if s.cited)

assert set(SECTION_KEYS) == set(DocumentDraft.model_fields), "the template and the draft must name the same sections"


def render(facts: ReleaseFacts, draft: DocumentDraft) -> str:
    parts = [
        f"# {facts.release} release notes (draft)",
        (
            f"Release {facts.version}, replacing {facts.previous_version} in production. "
            "Generated by Release Copilot; every factual sentence cites its evidence."
        ),
        "## Facts at a glance",
        facts_table(facts),
    ]
    for spec in SECTIONS:
        parts += [f"## {spec.title}", getattr(draft, spec.key).strip()]
    return "\n\n".join(parts) + "\n"
